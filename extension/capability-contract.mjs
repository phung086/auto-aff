// L070 — pure, deny-by-default capability contract for affiliate adapters.
// This module never reads social feeds, obtains credentials, or publishes content.
export const CAPABILITY_ACTIONS = Object.freeze(['read', 'analyze', 'draft', 'publish', 'report']);
export const CAPABILITY_STATES = Object.freeze(['unknown', 'disabled', 'awaiting-permission', 'draft-only', 'verified']);

const actions = new Set(CAPABILITY_ACTIONS);
const states = new Set(CAPABILITY_STATES);
const idValid = value => typeof value === 'string' && /^[A-Za-z0-9][A-Za-z0-9._:-]{0,99}$/.test(value);
const stamp = value => typeof value === 'string' && /^\d{4}-\d{2}-\d{2}T/.test(value) ? Date.parse(value) : NaN;
const deny = (reason, action) => ({ allowed: false, action, reason });

/**
 * The caller must independently authenticate both the platform API permission
 * and the human owner approval. A stored 'verified' string is NOT proof of either.
 * Scope names and source IDs are supplied by a trusted platform integration,
 * not generated by a model or inferred from a social post.
 */
export function evaluateCapability(adapter, action, context = {}) {
  if (!actions.has(action)) return deny('ACTION_UNKNOWN', action);
  if (!adapter || !idValid(adapter.adapterId) || !/^\d+\.\d+\.\d+$/.test(adapter.version ?? ''))
    return deny('ADAPTER_INVALID', action);
  if (adapter.enabled !== true) return deny('ADAPTER_DISABLED', action);
  if (adapter.market !== context.market) return deny('MARKET_MISMATCH', action);
  if (!idValid(context.accountId) || adapter.accountId !== context.accountId)
    return deny('ACCOUNT_MISMATCH', action);
  if (context.revoked === true) return deny('PERMISSION_REVOKED', action);

  const capability = adapter.capabilities?.[action];
  if (!capability || !states.has(capability.state)) return deny('CAPABILITY_UNKNOWN', action);
  if (capability.state !== 'verified') return deny('CAPABILITY_NOT_VERIFIED', action);
  if (capability.ownerApproved !== true) return deny('OWNER_APPROVAL_MISSING', action);
  if (!idValid(capability.accountId) || capability.accountId !== context.accountId)
    return deny('CAPABILITY_ACCOUNT_MISMATCH', action);
  if (action === 'publish' &&
      (!idValid(context.sourceId) || capability.sourceId !== context.sourceId))
    return deny('SOURCE_MISMATCH', action);

  const evidence = capability.evidence;
  const reviewedAt = stamp(evidence?.reviewedAt);
  const expiresAt = stamp(evidence?.expiresAt);
  const now = context.now ?? Date.now();
  if (typeof evidence?.sourceUrl !== 'string' || !/^https:\/\//.test(evidence.sourceUrl) ||
      !Number.isFinite(reviewedAt) || !Number.isFinite(expiresAt) ||
      !Number.isFinite(now) || reviewedAt > now || expiresAt <= reviewedAt)
    return deny('EVIDENCE_INVALID', action);
  if (expiresAt <= now) return deny('PERMISSION_EXPIRED', action);

  if (!Array.isArray(capability.requiredScopes) ||
      !capability.requiredScopes.every(scope => typeof scope === 'string' && scope.length > 0))
    return deny('SCOPES_UNKNOWN', action);
  if (!Array.isArray(context.grantedScopes) ||
      !capability.requiredScopes.every(scope => context.grantedScopes.includes(scope)))
    return deny('SCOPE_MISSING', action);
  return { allowed: true, action, reason: 'VERIFIED_CAPABILITY' };
}

/**
 * Offer metadata is seller-provided, not a product availability guarantee.
 * Validating a URL must never serialize, rewrite, shorten or retag it.
 */
export function validateAffiliateOffer(offer) {
  if (!offer || !idValid(offer.providerId) || !idValid(offer.offerId))
    throw new Error('Provider/offer ID không hợp lệ.');
  const raw = offer.affiliateUrl;
  if (typeof raw !== 'string' || !raw || raw.length > 4000 || /[\s<>]/u.test(raw))
    throw new Error('Link cộng tác viên không hợp lệ.');
  let parsed;
  try { parsed = new URL(raw); } catch { throw new Error('Link cộng tác viên không hợp lệ.'); }
  if (parsed.protocol !== 'https:' || !parsed.hostname || parsed.username || parsed.password)
    throw new Error('Link cần HTTPS và không chứa thông tin đăng nhập.');
  if (typeof offer.market !== 'string' || !/^[A-Z]{2}$/.test(offer.market))
    throw new Error('Mã thị trường không hợp lệ.');
  return Object.freeze({ providerId: offer.providerId, offerId: offer.offerId,
    market: offer.market, affiliateUrl: raw });
}
